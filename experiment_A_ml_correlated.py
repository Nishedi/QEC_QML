#!/usr/bin/env python3
"""Experiment A: standard 3-bit decoder vs classical ML under correlated X faults.

Input: CSV generated by generate_calibrated_training_data.py (calibration-based
SIMULATED shots; NOT raw physical-QPU measurements).

This script adds a TRANSPARENT, SYNTHETIC correlated bit-flip event to *observed*
three-bit strings: with probability p, it flips the DATA and ANC_A bits
simultaneously (110 in the DATA,ANC_A,ANC_B ordering).

The fault is injected AFTER measurement in classical post-processing. It is a
controlled proof of concept for the decoder; it is NOT a claim that these
correlations were measured on Odra or a full simulation of a quantum channel.

The ML model gets ONLY the two syndrome bits (s1, s2), never the true sent bit,
original measurement, or the injected-fault indicator. The sent bit is used
only for supervised labels in training and scoring on a held-out test split.

Requirements: pip install scikit-learn
Example:
    python experiment_A_ml_correlated.py --input training_data.csv \
        --output-dir experiment_A --rates 0,0.05,0.10,0.15,0.20,0.30 \
        --export-rate 0.15 --seed 42

Output:
    summary.csv                     Accuracy vs injected correlation rate
    learned_rules.csv               Learned decisions and train frequencies
    training_data_correlated.csv    Augmented data for the selected rate
    experiment_metadata.json        Sources, limitations, parameters
"""

import argparse
import csv
import hashlib
import json
import random
from collections import Counter, defaultdict
from pathlib import Path

from sklearn.tree import DecisionTreeClassifier

SYNDROMES = ((0, 0), (0, 1), (1, 0), (1, 1))


def syndrome(r):
    """r is (DATA, ANC_A, ANC_B), in that exact order."""
    return (r[0] ^ r[1], r[0] ^ r[2])


def standard_decode(r):
    """Majority-vote decoder, expressed as data-bit syndrome correction."""
    return r[0] ^ int(syndrome(r) == (1, 1))


def read_input(path):
    """Validate input without modifying original data or train/test splits."""
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        fields = list(reader.fieldnames or ())
        required = {"split", "sent", "received", "s1", "s2", "additional_x"}
        missing = required - set(fields)
        if missing:
            raise ValueError(f"Missing columns: {', '.join(sorted(missing))}")

        rows = []
        for number, raw in enumerate(reader, start=2):
            split = str(raw["split"]).strip().lower()
            if split not in ("train", "test"):
                raise ValueError(f"Row {number}: invalid split {split!r}")
            bit_str = str(raw["received"]).strip()
            if len(bit_str) != 3 or any(b not in "01" for b in bit_str):
                raise ValueError(f"Row {number}: invalid received {bit_str!r}")
            r = tuple(map(int, bit_str))
            sent_str = str(raw["sent"]).strip()
            if sent_str not in ("0", "1"):
                raise ValueError(f"Row {number}: invalid sent bit {sent_str!r}")
            sent = int(sent_str)
            s = syndrome(r)
            target = int(standard_decode(r) != sent)
            s1, s2 = str(raw["s1"]).strip(), str(raw["s2"]).strip()
            if (s1, s2) != (str(s[0]), str(s[1])):
                raise ValueError(f"Row {number}: syndrome does not match received")
            if str(raw["additional_x"]).strip() != str(target):
                raise ValueError(f"Row {number}: additional_x does not match sent/received")

            rows.append({"split": split, "sent": sent, "received": r, "original": raw})

    if not any(r["split"] == "train" for r in rows):
        raise ValueError("No training rows")
    if not any(r["split"] == "test" for r in rows):
        raise ValueError("No test rows")
    return fields, rows


def augment(rows, uniforms, probability):
    """Flips DATA and ANC_A together, independent of the prepared bit."""
    augmented = []
    for item, u in zip(rows, uniforms):
        r = item["received"]
        inject = int(u < probability)
        observed = ((r[0] ^ inject), (r[1] ^ inject), r[2])
        s = syndrome(observed)
        augmented.append({
            "split": item["split"],
            "sent": item["sent"],
            "original_received": r,
            "received": observed,
            "syndrome": s,
            "standard_decoded": standard_decode(observed),
            "additional_x": int(standard_decode(observed) != item["sent"]),
            "injected_pair_x_d_a": inject,
            "raw": item["original"],
        })
    return augmented


def score(augmented):
    train = [row for row in augmented if row["split"] == "train"]
    test = [row for row in augmented if row["split"] == "test"]
    model = DecisionTreeClassifier(max_depth=2, random_state=0)
    model.fit([r["syndrome"] for r in train], [r["additional_x"] for r in train])

    guesses = model.predict([r["syndrome"] for r in test])
    correct_std = sum(r["standard_decoded"] == r["sent"] for r in test)
    correct_ml = sum(
        (r["standard_decoded"] ^ int(pred)) == r["sent"]
        for r, pred in zip(test, guesses)
    )

    # An empirical per-syndrome lookup is included as a sanity baseline:
    # with only 4 input combinations, a deeper ML model is unnecessary.
    y_counts = defaultdict(Counter)
    for row in train:
        y_counts[row["syndrome"]][row["additional_x"]] += 1
    lookup = {
        s: int(y_counts[s][1] > y_counts[s][0])
        for s in SYNDROMES
    }
    correct_lookup = sum(
        (row["standard_decoded"] ^ lookup[row["syndrome"]]) == row["sent"]
        for row in test
    )
    learned = {s: int(model.predict([s])[0]) for s in SYNDROMES}

    n_test = len(test)
    metrics = {
        "train_n": len(train),
        "test_n": n_test,
        "injected_train": sum(r["injected_pair_x_d_a"] for r in train),
        "injected_test": sum(r["injected_pair_x_d_a"] for r in test),
        "standard_correct": correct_std,
        "ml_correct": correct_ml,
        "lookup_correct": correct_lookup,
        "standard_accuracy": correct_std / n_test,
        "ml_accuracy": correct_ml / n_test,
        "lookup_accuracy": correct_lookup / n_test,
        "gain_pp": 100 * (correct_ml - correct_std) / n_test,
        "ml_rules": learned,
    }
    rules = []
    for s in SYNDROMES:
        count = y_counts[s][0] + y_counts[s][1]
        rules.append({
            "syndrome": "".join(map(str, s)),
            "train_count": count,
            "train_error_rate_standard": y_counts[s][1] / count if count else "",
            "extra_x_ml": learned[s],
            "extra_x_frequency_lookup": lookup[s],
        })
    return metrics, rules


def save_augmented(path, fields, augmented):
    additional_cols = ["original_received", "injected_pair_x_d_a"]
    names = fields + [c for c in additional_cols if c not in fields]
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=names)
        writer.writeheader()
        for row in augmented:
            out = dict(row["raw"])
            out.update({
                "split": row["split"],
                "sent": row["sent"],
                "received": "".join(map(str, row["received"])),
                "s1": row["syndrome"][0],
                "s2": row["syndrome"][1],
                "standard_decoded": row["standard_decoded"],
                "additional_x": row["additional_x"],
                "original_received": "".join(map(str, row["original_received"])),
                "injected_pair_x_d_a": row["injected_pair_x_d_a"],
            })
            for i, field in enumerate(("received_d", "received_a", "received_b")):
                if field in fields:
                    out[field] = row["received"][i]
            if "observed_difference" in fields:
                out["observed_difference"] = "".join(
                    str(x ^ row["sent"]) for x in row["received"]
                )
            writer.writerow(out)


def parse_rates(text):
    rates = []
    for item in text.split(","):
        try:
            rate = float(item.strip())
        except ValueError as exc:
            raise ValueError(f"Invalid correlation rate {item!r}") from exc
        if not 0 <= rate <= 1:
            raise ValueError(f"Correlation rate outside [0,1]: {rate}")
        if rate not in rates:
            rates.append(rate)
    return sorted(rates)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--input", default="training_data.csv", help="CSV from the calibration-based simulator")
    parser.add_argument("--output-dir", default="experiment_A", help="Output directory")
    parser.add_argument("--rates", default="0,0.03,0.05,0.10,0.15,0.20,0.30",
                        help="Comma-separated probabilities of additional correlated X on D and A")
    parser.add_argument("--export-rate", type=float, default=0.15,
                        help="Export the augmented CSV at this correlation rate")
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    input_file = Path(args.input)
    if not input_file.is_file():
        parser.error(f"Input CSV not found: {input_file}")
    try:
        rates = parse_rates(args.rates)
    except ValueError as exc:
        parser.error(str(exc))
    if not 0 <= args.export_rate <= 1:
        parser.error("--export-rate must be in [0,1]")
    if args.export_rate not in rates:
        rates.append(args.export_rate)
        rates.sort()

    fields, rows = read_input(input_file)
    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    # One random uniform value per original row, reused for each p. This
    # makes the scenarios paired and avoids conflating p with new noise draws.
    rng = random.Random(args.seed)
    uniforms = [rng.random() for _ in rows]
    summaries = []
    all_rules = []
    saved_csv = None
    print(f"Input: {input_file} | {len(rows)} rows | seed={args.seed}")
    print("\nExtra correlated X on DATA and ANC_A (110):")
    print(f"{'p':>7} {'standard':>11} {'ML':>11} {'gain (pp)':>11} {'lookup':>11}  learned additional X")
    for rate in rates:
        augmented = augment(rows, uniforms, rate)
        metrics, rules = score(augmented)
        summaries.append({"correlation_probability": rate,
                          **{k: v for k, v in metrics.items() if k != "ml_rules"}})
        for rule in rules:
            all_rules.append({"correlation_probability": rate, **rule})
        s_labels = " ".join(f"{''.join(map(str, s))}:{metrics['ml_rules'][s]}" for s in SYNDROMES)
        print(f"{rate:7.2f} {metrics['standard_accuracy']:11.2%} "
              f"{metrics['ml_accuracy']:11.2%} {metrics['gain_pp']:+11.2f} "
              f"{metrics['lookup_accuracy']:11.2%}  {s_labels}")
        if abs(rate - args.export_rate) < 1e-12:
            saved_csv = out_dir / "training_data_correlated.csv"
            save_augmented(saved_csv, fields, augmented)
            print(f"       exported augmented dataset to {saved_csv}")

    summary_csv = out_dir / "summary.csv"
    with summary_csv.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(summaries[0].keys()))
        writer.writeheader()
        writer.writerows(summaries)
    rules_csv = out_dir / "learned_rules.csv"
    with rules_csv.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(all_rules[0].keys()))
        writer.writeheader()
        writer.writerows(all_rules)
    metadata = {
        "source": str(input_file),
        "source_sha256": hashlib.sha256(input_file.read_bytes()).hexdigest(),
        "experiment": "decoder-only stress test; correlated classical flips applied to measured bits",
        "injected_fault": "X on DATA and ANC_A together (mask 110 in D,A,B order)",
        "correlation_probabilities": rates,
        "export_rate": args.export_rate,
        "seed": args.seed,
        "features": ["s1", "s2"],
        "target": "additional_x recomputed after fault injection",
        "train_test_split": "preserved exactly from input CSV",
        "evaluation": "same held-out test rows for both methods",
        "limitations": [
            "Added correlated faults are synthetic, NOT observed on Odra 5.",
            "Faults are applied after the noisy measurement, not as quantum gates.",
            "The original CSV is calibration-based simulation, not hardware measurements.",
            "This is only classical decoding of computational basis states, NOT quantum coherence or entanglement protection.",
            "With only 4 syndromes an empirical lookup can match ML; a win over fixed majority decoding is not proof that ML is necessary.",
            "Results for synthetic faults do not establish a benefit on physical hardware.",
        ],
    }
    (out_dir / "experiment_metadata.json").write_text(
        json.dumps(metadata, indent=2, ensure_ascii=False), encoding="utf-8")

    print("\nInterpretation: ML should beat FIXED majority voting only when the more")
    print("likely correction for at least one syndrome differs from the fixed rule.")
    print("'lookup' is a non-neural frequency baseline using the same training data.")
    print("This experiment is a synthetic stress test, NOT evidence of actual")
    print("correlated faults on Odra 5 or an advantage over all non-ML decoders.")
    print(f"\nSaved: {summary_csv}, {rules_csv}, experiment_metadata.json")
    if saved_csv is not None:
        print(f"Augmented dataset: {saved_csv}")


if __name__ == "__main__":
    main()
